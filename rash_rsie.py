class Forked():
    def __init__(self, ram = [0] * MEMORY):
        self.SELFRAM = ram
    def execf(self,cmd):
        try:
            command = cmd.split(" ")[0]
            flags = cmd.split(" ")[1:] if len(cmd.split(" ")) > 1 else []
            if command in ROM.alias:
                if ROM.alias[command] in ROM.NEEDS_ELEVATED_PERMS and not PERMS:
                    raise UsrError("Command requires elevated permissions")
                self.SELFRAM = ROM.pin[ROM.alias[command]](flags, self.SELFRAM)
            else:
                raise UsrError(f"Command '{command}' not recognized. Did you mean 'run {command}'")
        except UsrError as e:
            printe("Error: Invalid command or arguments: " + str(e))
        except Exception as e:
            printe("Error: (Internal error): " + str(e))
    def merge(self):
        return self.SELFRAM

def main():
    printf(WELCOME_MSG)
    RUNNING = True
    iter = 0
    RAM = [0] * MEMORY
    while RUNNING:
        iter += 1
        user_input = input("Enter a command (type 'exit' to quit): " if iter == 1 else (f"root@{CURR_DIR}> " if PERMS else f"{USR}@{CURR_DIR}> "))
        if user_input.lower() == 'exit':
            RUNNING = False
            print("Exiting...")
        elif user_input.lower() == 'exitandclear':
            RUNNING = False
            ROM.clearconsole([], [])
        elif user_input.lower() == 'sjelter':
            printf("Sjelter?")
        elif user_input != "":
            fork = Forked(RAM)
            fork.execf(user_input)
            RAM = fork.merge()
            fork.SELFRAM = None


if __name__ == "__main__":
    main()
    