def col_print(lines, term_width=None, indent=0, pad=2):
    """Print list of strings in multiple columns
    Original: https://gist.github.com/critiqjo/2ca84db26daaeb1715e1
    Adjusted: https://gist.github.com/Nachtalb/8a85c0793b4bea0a102b7414be5888d4
    """
    if not term_width:
        size = shutil.get_terminal_size((80, 20))
        term_width = size.columns

    n_lines = len(lines)
    if n_lines == 0:
        return

    col_width = max(len(line) for line in lines)
    n_cols = int((term_width + pad - indent) / (col_width + pad))
    n_cols = min(n_lines, max(1, n_cols))

    col_len = int(n_lines / n_cols) + (0 if n_lines % n_cols == 0 else 1)
    if (n_cols - 1) * col_len >= n_lines:
        n_cols -= 1

    cols = [lines[i * col_len: i * col_len + col_len] for i in range(n_cols)]

    rows = list(zip(*cols))
    rows_missed = zip(*[col[len(rows):] for col in cols[:-1]])
    rows.extend(rows_missed)

    for row in rows:
        printf(" " * indent + (" " * pad).join(line.ljust(col_width) for line in row))


def pull_url(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url + f"?t={int(time.time())}")) as response:
            file_contents = response.read().decode('utf-8')
        return file_contents
    except Exception as e:
        raise UsrError(str(e))

def base64(num):
    BASE64_ALPHABET = " !\"#\\$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_abcdefghijklmnopqrstuvwxyz{|}~`00000000"
    if num == 0:
        return BASE64_ALPHABET[0]
    
    arr = []
    base = 99
    while num:
        num, rem = divmod(num, base)
        arr.append(BASE64_ALPHABET[rem])
        
    return ''.join(reversed(arr))
def base10(b64_str):
    BASE64_ALPHABET = " !\"#\\$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_abcdefghijklmnopqrstuvwxyz{|}~`00000000"
    CHAR_TO_INDEX = {char: index for index, char in enumerate(BASE64_ALPHABET)}
    num = 0
    for char in b64_str:
        num = num * 99 + CHAR_TO_INDEX[char]
    return num

